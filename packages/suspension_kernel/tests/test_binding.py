def test_build_driver_survives_compiler_output_it_cannot_decode(
    tmp_path: Path,
) -> None:
    """
    Undecodable compiler output must not be reported as a crash in the driver.

    The repository path contains non-ASCII characters, so the compiler's own
    diagnostics carry bytes that a locale codec (GBK on the machine this was fixed
    on) cannot decode.  Decoding with the locale raised ``UnicodeDecodeError``
    from inside the driver, so a failed compile read as "the driver is broken".

    The contract asserted here is that the bytes are *survivable*, not that they
    are recovered: they are GBK in a UTF-8 world, so replacement characters are
    the correct outcome.  What matters is that the driver returns normally on
    success and reports a failed command as a failed command.  The stub emits
    bytes that are invalid in UTF-8 as well, so a wrong codec and a malformed
    sequence are both covered.
    """
    from suspension_kernel.binding.build import _run

    noisy = tmp_path / "noisy_compiler.py"
    noisy.write_text(
        "import sys\n"
        "sys.stdout.buffer.write('错误'.encode('gbk') + b'\\xff')\n",
        encoding="utf-8",
    )
    failed = tmp_path / "failed_compiler.py"
    failed.write_text(
        "import sys\n"
        "sys.stdout.buffer.write('错误'.encode('gbk') + b'\\xff\\n')\n"
        "raise SystemExit(1)\n",
        encoding="utf-8",
    )

    completed = _run([sys.executable, str(noisy)], cwd=tmp_path)
    # Decoded without raising, and the undecodable bytes became replacements.
    assert completed.stdout
    assert "\ufffd" in completed.stdout

    with pytest.raises(RuntimeError) as captured:
        _run([sys.executable, str(failed)], cwd=tmp_path)
    assert "command failed with exit code 1" in str(captured.value)
